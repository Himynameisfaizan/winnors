<!-- Advanced Scroll & Counter Script -->
<script>
    document.addEventListener("DOMContentLoaded", function () {
        // 1. Scroll Reveal Logic (Same as before but extended)
        const reveals = document.querySelectorAll('.reveal');
        const appearOptions = { threshold: 0.15, rootMargin: "0px 0px -50px 0px" };

        const appearOnScroll = new IntersectionObserver(function (entries, observer) {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('active');

                    // 2. Counter Animation Logic
                    // Check if the revealed element contains a stat-number
                    const counter = entry.target.querySelector('.stat-number');
                    if (counter && !counter.classList.contains('counted')) {
                        counter.classList.add('counted'); // Prevent re-running
                        const target = +counter.getAttribute('data-target');
                        const speed = 200; // Lower is faster
                        const suffix = counter.querySelector('span').outerHTML; // Keep the + or % symbol

                        const updateCount = () => {
                            // Extract just the number text
                            const current = +counter.innerText.replace(/[^0-9]/g, '');
                            const inc = target / speed;

                            if (current < target) {
                                counter.innerHTML = Math.ceil(current + inc) + ' ' + suffix;
                                setTimeout(updateCount, 10); // Update every 10ms
                            } else {
                                counter.innerHTML = target + ' ' + suffix;
                            }
                        };
                        updateCount();
                    }
                    observer.unobserve(entry.target);
                }
            });
        }, appearOptions);

        reveals.forEach(reveal => appearOnScroll.observe(reveal));
    });
</script>

